export function getBookById(id) {
  return books.find((b) => b.id === id);
}

export function getRelatedBooks(book) {
  return book.relatedIds.map((id) => getBookById(id)).filter(Boolean);
}

export function getRecommendedBooks(orderHistory = []) {
  if (!orderHistory.length) return books.slice(0, 6);
  const boughtCategories = [...new Set(orderHistory.map((o) => getBookById(o.bookId)?.category))];
  const scored = books
    .filter((b) => !orderHistory.find((o) => o.bookId === b.id))
    .map((b) => ({ ...b, score: boughtCategories.includes(b.category) ? 2 : 1 }))
    .sort((a, b) => b.score - a.score || b.rating - a.rating);
  return scored.slice(0, 6);
}
